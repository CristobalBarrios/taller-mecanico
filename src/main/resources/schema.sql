CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 nombre VARCHAR(100) NOT NULL,
 usuario VARCHAR(60) NOT NULL UNIQUE,
 clave VARCHAR(100) NOT NULL,
 rol VARCHAR(20) NOT NULL,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 CHECK (rol IN ('ADMINISTRADOR','RECEPCION','MECANICO','BODEGUERO'))
);
CREATE TABLE IF NOT EXISTS clientes (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 nombre VARCHAR(100) NOT NULL,
 nit VARCHAR(30) NOT NULL,
 telefono VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS vehiculos (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 cliente_id BIGINT NOT NULL,
 placa VARCHAR(20) NOT NULL UNIQUE,
 marca VARCHAR(60) NOT NULL,
 modelo VARCHAR(60) NOT NULL,
 anio INT NOT NULL,
 FOREIGN KEY (cliente_id) REFERENCES clientes(id)
);
CREATE TABLE IF NOT EXISTS ordenes (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 vehiculo_id BIGINT NOT NULL,
 mecanico_id BIGINT NOT NULL,
 motivo VARCHAR(1000) NOT NULL,
 estado VARCHAR(30) NOT NULL DEFAULT 'RECIBIDO',
 ingreso TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 salida TIMESTAMP NULL,
 mano_obra DECIMAL(12,2) NOT NULL DEFAULT 0,
 FOREIGN KEY (vehiculo_id) REFERENCES vehiculos(id),
 FOREIGN KEY (mecanico_id) REFERENCES usuarios(id),
 CHECK (estado IN ('RECIBIDO','DIAGNOSTICADO','EN_REPARACION','TERMINADO','ENTREGADO')),
 CHECK (mano_obra >= 0)
);
CREATE TABLE IF NOT EXISTS diagnosticos (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 orden_id BIGINT NOT NULL,
 usuario_id BIGINT NOT NULL,
 descripcion VARCHAR(2000) NOT NULL,
 reparacion VARCHAR(2000) NOT NULL,
 fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (orden_id) REFERENCES ordenes(id),
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS repuestos (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 codigo VARCHAR(40) NOT NULL UNIQUE,
 nombre VARCHAR(100) NOT NULL,
 precio DECIMAL(12,2) NOT NULL,
 stock INT NOT NULL DEFAULT 0,
 minimo INT NOT NULL DEFAULT 2,
 CHECK (precio >= 0), CHECK (stock >= 0), CHECK (minimo >= 0)
);
CREATE TABLE IF NOT EXISTS solicitudes (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 orden_id BIGINT NOT NULL,
 repuesto_id BIGINT NOT NULL,
 cantidad INT NOT NULL,
 precio_unitario DECIMAL(12,2) NULL,
 estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
 fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (orden_id) REFERENCES ordenes(id),
 FOREIGN KEY (repuesto_id) REFERENCES repuestos(id),
 CHECK (cantidad > 0), CHECK (estado IN ('PENDIENTE','DESPACHADO','RECHAZADO'))
);
CREATE TABLE IF NOT EXISTS movimientos (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 repuesto_id BIGINT NOT NULL,
 usuario_id BIGINT NOT NULL,
 cantidad INT NOT NULL,
 motivo VARCHAR(300) NOT NULL,
 fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (repuesto_id) REFERENCES repuestos(id),
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS facturas (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 orden_id BIGINT NOT NULL UNIQUE,
 cliente_nombre VARCHAR(100) NOT NULL,
 cliente_nit VARCHAR(30) NOT NULL,
 mano_obra DECIMAL(12,2) NOT NULL,
 repuestos DECIMAL(12,2) NOT NULL,
 total DECIMAL(12,2) NOT NULL,
 fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (orden_id) REFERENCES ordenes(id)
);
CREATE TABLE IF NOT EXISTS historial (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 usuario_id BIGINT NOT NULL,
 accion VARCHAR(100) NOT NULL,
 detalle VARCHAR(1000) NOT NULL,
 fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS configuracion (
 id INT PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL,
 telefono VARCHAR(30) NOT NULL,
 direccion VARCHAR(200) NOT NULL
);
